# usage: tools/offsetgen/offsetgen.sh openssl-3.6.2 [openssl-3.5.4 ...] > internal/tls/openssl/offsets_gen.go
#
# For each upstream OpenSSL tag: shallow-clone it, configure and generate the
# internal headers, then compile tools/offsetgen/openssl_offset.c against the
# release's own ssl/ssl_local.h and print its struct offsets as a Go map entry.
# OpenSSL sources are never vendored; everything lives under a temp dir that is
# removed on exit.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
probe="${here}/openssl_offset.c"
repo="${OPENSSL_REPO:-https://github.com/openssl/openssl.git}"

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

printf '// SPDX-License-Identifier: AGPL-3.0-only\n\n'
printf '// Code generated by tools/offsetgen; DO NOT EDIT.\n\n'
printf 'package openssl\n\n'
printf 'var offsets = map[string]Offset{\n'

for tag in "$@"
do
	src="${work}/${tag}"
	git clone --quiet --depth 1 --branch "${tag}" "${repo}" "${src}"
	# no-shared no-tests keeps the configure fast; the layout the probe reads is
	# the default one, which matches the distribution libraries (see openssl.go).
	(cd "${src}" && ./Configure no-shared no-tests > /dev/null && make -s build_generated)
	gcc -I"${src}" -I"${src}/include" "${probe}" -o "${src}/openssl_offset"
	"${src}/openssl_offset"
done

printf '}\n'
