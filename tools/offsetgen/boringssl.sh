# usage: ANDROID_NDK=<ndk dir> tools/offsetgen/boringssl.sh 15 [16 ...] > internal/tls/boringssl/offsets_gen.go
#
# For each Android release: shallow-clone the android<release>-release branch
# of platform/external/boringssl, the BoringSSL Conscrypt is built from, then
# compile tools/offsetgen/boringssl_offset.cc against its own internal headers
# with the NDK's clang for x86_64 and aarch64 Android (bionic, libc++), and
# read the offsets from the assembly, so nothing is run for the other
# architecture. BoringSSL sources are never vendored; everything lives under a
# temp dir that is removed on exit.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
probe="${here}/boringssl_offset.cc"
repo="${BORINGSSL_REPO:-https://android.googlesource.com/platform/external/boringssl}"
ndk="${ANDROID_NDK:?set ANDROID_NDK to an Android NDK directory}"
# the API level only picks the bionic headers, the structs the probe reads have no libc types
api="${ANDROID_API:-35}"
clang="${ndk}/toolchains/llvm/prebuilt/linux-x86_64/bin/clang++"

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

printf '// SPDX-License-Identifier: AGPL-3.0-only\n\n'
printf '// Code generated by tools/offsetgen; DO NOT EDIT.\n\n'
printf 'package boringssl\n\n'
printf 'var offsets = map[string]map[string]Offset{\n'

for release in "$@"
do
	src="${work}/${release}"
	git clone --quiet --depth 1 --branch "android${release}-release" "${repo}" "${src}"
	printf '\t"%s": {\n' "${release}"

	for arch in amd64:x86_64 arm64:aarch64
	do
		# x86_64 emits .quad, aarch64 .xword for the 8 byte constants
		"${clang}" --target="${arch#*:}-linux-android${api}" -std=c++17 -O2 -Wno-invalid-offsetof -S -o "${src}/probe-${arch%%:*}.s" -I"${src}/src" -I"${src}/src/include" "${probe}"
		awk -v arch="${arch%%:*}" '
			/^decerter_offset_[a-z0-9_]+:/ { name = substr($1, 17, length($1) - 17); next }
			name != "" && ($1 == ".quad" || $1 == ".xword") { value[name] = $2; name = "" }
			END {
				if (!("version" in value) || !("version_in_s3" in value) || !("s3" in value) || !("client_random" in value)) { exit 1 }
				printf "\t\t\"%s\": {Version: 0x%x, VersionInS3: %s, S3: 0x%x, ClientRandom: 0x%x},\n", arch, value["version"], (value["version_in_s3"] == 1) ? "true" : "false", value["s3"], value["client_random"]
			}' "${src}/probe-${arch%%:*}.s"
	done

	printf '\t},\n'
done

printf '}\n'
